# Each glyph: 16 bytes = 8 columns × 16 rows (1 byte per column, LSB=top pixel)
# We define glyphs as strings of 16 rows × 8 cols, '#'=on '.'=off

def make_glyph(rows):
    """rows: list of 16 strings, each 8 chars. '#'=pixel on, else off.
    Returns 16 bytes: byte[col*2+0] = rows 0-7 of column col,
                       byte[col*2+1] = rows 8-15 of column col."""
    out = []
    for col in range(8):
        lo = 0  # rows 0-7
        hi = 0  # rows 8-15
        for row in range(16):
            if row < len(rows) and col < len(rows[row]) and rows[row][col] == '#':
                if row < 8:
                    lo |= (1 << row)
                else:
                    hi |= (1 << (row - 8))
        out.append(lo)
        out.append(hi)
    return bytes(out)

def r(*args):
    """Helper: 16 strings of 8 chars each"""
    return list(args)

